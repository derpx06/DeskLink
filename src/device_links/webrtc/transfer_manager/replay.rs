//! Scenario transcripts S1-S7 (`testdata/transfers_v2/*.json`), replayed
//! against this desk's engines.
//!
//! The same files are carried, byte for byte, by the phone's tests. A
//! transcript is a list of steps `{from: sender|receiver|test, ...}`. A side
//! replays it against its own engine: every step from the *other* side is fed
//! in (controls through `on_control`, frames through `on_frame`), every `test`
//! event for this side is applied, and the engine's outputs must equal this
//! side's own steps, in order. Controls compare as parsed JSON (minus the keys
//! in `ignore`); frames compare as groups of one block: pass, block, count and
//! the SHA-256 of their concatenated bytes. The files are generated by
//! `generate.py` with nothing but `hashlib`, so they are an independent check.

use std::fs;
use std::path::PathBuf;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::mpsc::channel;
use std::sync::{Arc, Mutex};
use std::time::{Duration, Instant, SystemTime};

use serde_json::Value;

use super::super::file_protocol::{id_bytes, parse_frame, FileControl, BLOCK_BYTES};
use super::store::ReceiveCheckpoint;
use super::{Completed, FileLink, Tunables, WebRtcTransferManager};
use crate::device_links::webrtc::WebRtcWireBinding;

type Manager = WebRtcTransferManager;

enum Out {
    Control(Value),
    Frame(Vec<u8>),
}

/// What an engine sent, in order; a transcript's `spoil-next-done` event
/// damages the next `done` it sends.
struct Recorder {
    out: Mutex<Vec<Out>>,
    spoil_done: AtomicBool,
}

impl FileLink for Recorder {
    fn send_control(&self, control: &FileControl) -> Result<(), String> {
        let mut value = serde_json::to_value(control).unwrap();
        if value["action"] == "done" && self.spoil_done.swap(false, Ordering::SeqCst) {
            value["fileHash"] = Value::String("00".repeat(32));
        }
        self.out.lock().unwrap().push(Out::Control(value));
        Ok(())
    }

    fn send_frame(&self, frame: Vec<u8>) -> Result<(), String> {
        self.out.lock().unwrap().push(Out::Frame(frame));
        Ok(())
    }

    fn buffered(&self) -> u64 {
        0
    }
}

/// The file of a transcript: `byte(i) = (((i * 2654435761) mod 2^32) >> 13) & 255`,
/// with the transcript's overrides (xor at an offset).
fn content(length: u64, overrides: &[Value]) -> Vec<u8> {
    let mut data: Vec<u8> = (0..length)
        .map(|i| (((i * 2_654_435_761) & 0xFFFF_FFFF) >> 13) as u8)
        .collect();
    for item in overrides {
        let at = item["offset"].as_u64().unwrap() as usize;
        data[at] ^= item["xor"].as_u64().unwrap() as u8;
    }
    data
}

fn sha(bytes: &[u8]) -> [u8; 32] {
    openssl::sha::sha256(bytes)
}

/// The frame messages of block `block` of `data`.
fn frames_of(data: &[u8], block: u64, pass: u8, id: &str) -> Vec<Vec<u8>> {
    let capacity = super::super::file_protocol::payload_capacity(61_440);
    let start = (block * BLOCK_BYTES) as usize;
    let end = (start + BLOCK_BYTES as usize).min(data.len());
    let body = &data[start..end];
    let hash = sha(body);
    let mut frames = Vec::new();
    let mut at = 0;
    while at < body.len() {
        let length = capacity.min(body.len() - at);
        let last = at + length == body.len();
        let header = super::super::file_protocol::FrameHeader {
            last_of_block: last,
            pass,
            transfer: id_bytes(id).unwrap(),
            block_index: block as u32,
            offset: (start + at) as u64,
            length: length as u32,
        };
        let mut frame = Vec::new();
        header.write(&mut frame);
        frame.extend_from_slice(&body[at..at + length]);
        if last {
            frame.extend_from_slice(&hash);
        }
        frames.push(frame);
        at += length;
    }
    frames
}

fn digest(frames: &[Vec<u8>]) -> String {
    super::super::file_protocol::hex(&sha(&frames.concat()))
}

fn wire(me: &str, peer: &str, ids: &Value) -> WebRtcWireBinding {
    WebRtcWireBinding {
        sender_device_id: me.to_string(),
        peer_device_id: peer.to_string(),
        session_id: ids["sessionId"].as_u64().unwrap(),
        generation: ids["generation"].as_u64().unwrap(),
    }
}

fn fast() -> Tunables {
    Tunables {
        checkpoint_blocks: 2,
        checkpoint_after: Duration::from_millis(40),
        report_every: Duration::from_millis(5),
        ..Tunables::default()
    }
}

/// Waits until nothing more is being produced.
fn quiet(manager: &Manager, recorder: &Recorder) {
    let deadline = Instant::now() + Duration::from_secs(20);
    let mut last = usize::MAX;
    let mut steady = 0;
    while steady < 3 {
        assert!(Instant::now() < deadline, "the engine never went quiet");
        manager.probe(|_| ());
        std::thread::sleep(Duration::from_millis(25));
        let now = recorder.out.lock().unwrap().len();
        if now == last {
            steady += 1;
        } else {
            steady = 0;
            last = now;
        }
    }
}

fn without(value: &Value, ignore: &[String]) -> Value {
    let mut copy = value.clone();
    if let Some(map) = copy.as_object_mut() {
        for key in ignore {
            map.remove(key);
        }
    }
    copy
}

struct Run {
    name: String,
    doc: Value,
    ignore: Vec<String>,
    base: PathBuf,
}

impl Run {
    fn files(&self) -> (Vec<u8>, Vec<u8>) {
        let length = self.doc["file"]["length"].as_u64().unwrap();
        let original = content(length, &[]);
        let sender = match self.doc["senderFile"]["overrides"].as_array() {
            Some(overrides) => content(length, overrides),
            None => original.clone(),
        };
        (original, sender)
    }

    fn id(&self) -> &str {
        self.doc["ids"]["transferId"].as_str().unwrap()
    }

    fn token(&self) -> &str {
        self.doc["ids"]["token"].as_str().unwrap()
    }

    /// Compares what `side` sent with what the transcript says it sent.
    fn compare(&self, side: &str, recorder: &Recorder, sender_file: &[u8]) {
        let out = recorder.out.lock().unwrap();
        let mut at = 0;
        for (index, step) in self.doc["steps"].as_array().unwrap().iter().enumerate() {
            if step["from"] != side {
                continue;
            }
            let context = format!("{} {side} step {index}", self.name);
            if let Some(expected) = step.get("control") {
                let Some(Out::Control(actual)) = out.get(at) else {
                    panic!("{context}: expected {expected}, the engine sent nothing or a frame");
                };
                assert_eq!(
                    without(actual, &self.ignore),
                    without(expected, &self.ignore),
                    "{context}"
                );
                at += 1;
            } else if let Some(group) = step.get("blockFrames") {
                let count = group["frames"].as_u64().unwrap() as usize;
                let mut frames = Vec::new();
                for _ in 0..count {
                    let Some(Out::Frame(frame)) = out.get(at) else {
                        panic!("{context}: expected a frame of block {}", group["block"]);
                    };
                    let parsed = parse_frame(frame).unwrap();
                    assert_eq!(
                        (
                            u64::from(parsed.header.block_index),
                            u64::from(parsed.header.pass)
                        ),
                        (
                            group["block"].as_u64().unwrap(),
                            group["pass"].as_u64().unwrap()
                        ),
                        "{context}: a frame of the wrong block or pass"
                    );
                    frames.push(frame.clone());
                    at += 1;
                }
                assert_eq!(
                    digest(&frames),
                    group["sha256"].as_str().unwrap(),
                    "{context}"
                );
                let _ = sender_file;
            }
        }
        assert_eq!(
            out.len(),
            at,
            "{} {side}: the engine sent more than the transcript",
            self.name
        );
    }

    fn replay_receiver(&self) {
        let ids = &self.doc["ids"];
        let (original, sender_file) = self.files();
        let length = original.len() as u64;
        let dir = self.base.join("receiver");
        let manager = Arc::new(
            Manager::with(
                dir.join("state"),
                dir.join("dl"),
                fast(),
                super::FILE_QUEUE_MAX_BYTES,
            )
            .unwrap(),
        );
        let recorder = Arc::new(Recorder {
            out: Mutex::new(Vec::new()),
            spoil_done: AtomicBool::new(false),
        });
        let (tx, completed) = channel::<Completed>();
        let tx = Mutex::new(tx);
        manager.set_completion_hook(move |c| {
            let _ = tx.lock().unwrap().send(c.clone());
        });
        manager.attach(
            wire(
                ids["receiver"].as_str().unwrap(),
                ids["sender"].as_str().unwrap(),
                ids,
            ),
            recorder.clone(),
        );
        if let Some(blocks) = self.doc["receiverHolds"]["blocks"].as_u64() {
            // A checkpoint of the first blocks, as a crashed receiver left it.
            let hashes: Vec<[u8; 32]> = original
                .chunks(BLOCK_BYTES as usize)
                .take(blocks as usize)
                .map(sha)
                .collect();
            let id = self.id().to_string();
            let token = self.token().to_string();
            let sender = ids["sender"].as_str().unwrap().to_string();
            let name = self.doc["file"]["name"].as_str().unwrap().to_string();
            let held = original[..(blocks * BLOCK_BYTES) as usize].to_vec();
            manager.probe(move |engine| {
                use std::io::Write;
                let mut part = engine.store.create_part(&id).unwrap();
                part.write_all(&held).unwrap();
                part.sync_all().unwrap();
                engine
                    .store
                    .save_receive(
                        &ReceiveCheckpoint {
                            transfer_id: id,
                            device_id: sender,
                            token,
                            filename: name.clone(),
                            destination_name: name,
                            total_size: length,
                            mtime: 1_700_000_000_000,
                            blocks_done: blocks,
                            clipboard: false,
                            capture_id: None,
                            folder: None,
                            content_sha256: None,
                        },
                        &hashes,
                    )
                    .unwrap();
            });
        }
        for step in self.doc["steps"].as_array().unwrap() {
            let from = step["from"].as_str().unwrap();
            if from == "sender" {
                if let Some(control) = step.get("control") {
                    manager.on_control(
                        FileControl::from_json(control.to_string().as_bytes()).unwrap(),
                    );
                } else if let Some(group) = step.get("blockFrames") {
                    let frames = frames_of(
                        &sender_file,
                        group["block"].as_u64().unwrap(),
                        group["pass"].as_u64().unwrap() as u8,
                        self.id(),
                    );
                    assert_eq!(
                        digest(&frames),
                        group["sha256"].as_str().unwrap(),
                        "{}: bad transcript",
                        self.name
                    );
                    for frame in frames {
                        manager.on_frame(frame);
                    }
                }
                quiet(&manager, &recorder);
            } else if from == "test" && step["side"] == "receiver" {
                match step["event"].as_str().unwrap() {
                    "backlog-on" => manager.probe(|engine| {
                        engine
                            .shared
                            .queued
                            .store(engine.tun.queue_pause, Ordering::SeqCst);
                        engine.apply_backlog();
                    }),
                    "backlog-off" => manager.probe(|engine| {
                        engine.shared.queued.store(0, Ordering::SeqCst);
                        engine.apply_backlog();
                    }),
                    other => panic!("{}: unknown receiver event {other}", self.name),
                }
                quiet(&manager, &recorder);
            }
        }
        self.compare("receiver", &recorder, &sender_file);
        // The end state.
        let open = manager.probe(|engine| engine.incoming_ids().len());
        if self.doc["final"]["slotsFree"] == true {
            assert_eq!(open, 0, "{}: a receive slot is still held", self.name);
        } else if self.doc["final"]["slotsFree"] == false {
            assert!(open > 0, "{}: the transfer should still be open", self.name);
        }
        match self.doc["final"]["receiverPublished"].as_bool() {
            Some(true) => {
                let got = completed
                    .recv_timeout(Duration::from_secs(10))
                    .unwrap_or_else(|_| panic!("{}: nothing was published", self.name));
                let wanted = if self.doc["final"]["publishedIsSenderFile"] == true {
                    &sender_file
                } else {
                    &original
                };
                assert_eq!(&fs::read(got.path).unwrap(), wanted, "{}", self.name);
            }
            Some(false) => {
                assert!(completed.try_recv().is_err(), "{}: published", self.name);
                assert!(
                    fs::read_dir(dir.join("dl")).map_or(true, |mut d| d.next().is_none()),
                    "{}: a file in downloads",
                    self.name
                );
            }
            None => {}
        }
    }

    fn replay_sender(&self) {
        let ids = &self.doc["ids"];
        let (_, sender_file) = self.files();
        let dir = self.base.join("sender");
        fs::create_dir_all(&dir).unwrap();
        let source = dir.join(self.doc["file"]["name"].as_str().unwrap());
        fs::write(&source, &sender_file).unwrap();
        let mtime = self.doc["file"]["mtime"].as_u64().unwrap();
        fs::File::options()
            .write(true)
            .open(&source)
            .unwrap()
            .set_modified(SystemTime::UNIX_EPOCH + Duration::from_millis(mtime))
            .unwrap();
        let manager = Arc::new(
            Manager::with(
                dir.join("state"),
                dir.join("dl"),
                fast(),
                super::FILE_QUEUE_MAX_BYTES,
            )
            .unwrap(),
        );
        let recorder = Arc::new(Recorder {
            out: Mutex::new(Vec::new()),
            spoil_done: AtomicBool::new(false),
        });
        manager.attach(
            wire(
                ids["sender"].as_str().unwrap(),
                ids["receiver"].as_str().unwrap(),
                ids,
            ),
            recorder.clone(),
        );
        manager
            .start_send_fixed(&source, self.id(), self.token())
            .unwrap();
        quiet(&manager, &recorder);
        for step in self.doc["steps"].as_array().unwrap() {
            let from = step["from"].as_str().unwrap();
            if from == "receiver" {
                let control = step
                    .get("control")
                    .expect("the receiver sends controls only");
                manager.on_control(FileControl::from_json(control.to_string().as_bytes()).unwrap());
                quiet(&manager, &recorder);
            } else if from == "test" && step["side"] == "sender" {
                match step["event"].as_str().unwrap() {
                    "spoil-next-done" => recorder.spoil_done.store(true, Ordering::SeqCst),
                    "source-read-error" => manager.probe(|engine| {
                        for outgoing in &mut engine.outgoing {
                            outgoing.fail_read = true;
                        }
                    }),
                    other => panic!("{}: unknown sender event {other}", self.name),
                }
                quiet(&manager, &recorder);
            }
        }
        self.compare("sender", &recorder, &sender_file);
        if self.doc["final"]["slotsFree"] == true {
            assert_eq!(
                manager.probe(|engine| engine.outgoing.len()),
                0,
                "{}: a send slot is still held",
                self.name
            );
        }
    }
}

fn replay(name: &str, text: &str) {
    let doc: Value = serde_json::from_str(text).unwrap();
    assert_eq!(doc["scenario"], name);
    let ignore: Vec<String> = doc["ignore"]
        .as_array()
        .unwrap()
        .iter()
        .map(|key| key.as_str().unwrap().to_string())
        .collect();
    let base = std::env::temp_dir().join(format!(
        "desklink-replay-{name}-{}",
        uuid::Uuid::new_v4().simple()
    ));
    let run = Run {
        name: name.to_string(),
        doc,
        ignore,
        base,
    };
    let sides: Vec<String> = run.doc["replay"]
        .as_array()
        .unwrap()
        .iter()
        .map(|side| side.as_str().unwrap().to_string())
        .collect();
    for side in &sides {
        match side.as_str() {
            "sender" => run.replay_sender(),
            "receiver" => run.replay_receiver(),
            other => panic!("unknown side {other}"),
        }
    }
    let _ = fs::remove_dir_all(&run.base);
}

macro_rules! scenario {
    ($test:ident, $name:literal, $title:literal) => {
        #[doc = $title]
        #[test]
        fn $test() {
            replay(
                $name,
                include_str!(concat!("../testdata/transfers_v2/", $name, ".json")),
            );
        }
    };
}

