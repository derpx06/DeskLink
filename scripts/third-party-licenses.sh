#!/bin/sh
# Writes THIRD_PARTY_LICENSES: every crate in Cargo.lock (the app and the
# relay types it links) with its licence expression and the licence texts
# found in its source, each distinct text once. Offline: `cargo metadata`
# reads the crates already in ~/.cargo/registry (run `cargo fetch` first on a
# fresh machine). Usage: scripts/third-party-licenses.sh [output]
set -e
cd "$(dirname "$0")/.."
out=${1:-THIRD_PARTY_LICENSES}
# The app and the relay binary the release also ships have separate lock
# files; both sets of crates are listed.
{ cargo metadata --format-version 1 --locked --offline
  cargo metadata --format-version 1 --locked --offline --manifest-path relay/Cargo.toml
} | python3 -c '
import sys, json, os, glob, hashlib
decoder = json.JSONDecoder()
raw = sys.stdin.read()
documents, at = [], 0
while at < len(raw):
    while at < len(raw) and raw[at].isspace():
        at += 1
    if at >= len(raw):
        break
    document, at = decoder.raw_decode(raw, at)
    documents.append(document)
packages = {}
for meta in documents:
    for pkg in meta["packages"]:
        packages[(pkg["name"], pkg["version"])] = pkg
meta = {"packages": list(packages.values())}
texts = {}      # sha -> (text, [crates])
rows = []
for pkg in sorted(meta["packages"], key=lambda p: (p["name"], p["version"])):
    if pkg["name"] in ("desklink", "desklink-relay"):
        continue
    directory = os.path.dirname(pkg["manifest_path"])
    files = []
    if pkg.get("license_file"):
        files.append(os.path.join(directory, pkg["license_file"]))
    for pattern in ("LICENSE*", "LICENCE*", "COPYING*", "UNLICENSE*"):
        files += glob.glob(os.path.join(directory, pattern))
    seen = set()
    label = pkg["name"] + " " + pkg["version"]
    rows.append((label, pkg.get("license") or "see source", pkg.get("repository") or ""))
    for path in files:
        if path in seen or not os.path.isfile(path):
            continue
        seen.add(path)
        text = open(path, errors="replace").read().strip()
        key = hashlib.sha256(text.encode()).hexdigest()
        texts.setdefault(key, (text, []))[1].append(label)
print("Third-party software in DeskLink\n")
print("DeskLink itself is GPL-3.0-or-later (see COPYING). It links the crates")
print("below; each is under the licence shown. Generated by")
print("scripts/third-party-licenses.sh from Cargo.lock.\n")
print("== Crates ==\n")
for label, lic, repo in rows:
    print(f"{label}: {lic}" + (f" ({repo})" if repo else ""))
print("\n== Licence texts ==")
for text, crates in sorted(texts.values(), key=lambda t: t[1][0]):
    print("\n" + "-" * 72)
    print("Used by: " + ", ".join(crates))
    print("-" * 72)
    print(text)
' > "$out"
echo "wrote $out ($(wc -l < "$out") lines)"
